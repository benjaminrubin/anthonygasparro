#!/usr/bin/env python3
"""Generate web-sized WebP copies of the site's images.

    python3 tools/optimize-images.py        (needs Pillow: pip install pillow)

The originals in img/ are never modified. For every original this writes one or
two resized WebP files under img/optimized/ (thumb_0.jpg -> thumb_0.jpg.webp,
thumb_0.jpg-640.webp) and records them in
js/image-manifest.js. The gallery scripts look each image up in that manifest
and fall back to the original file when there is no entry, so a newly added
image works straight away; re-run this script afterwards to make it fast.
"""
import json
import os
import sys

from PIL import Image, ImageOps

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT_DIR = "img/optimized"
MANIFEST = "js/image-manifest.js"
QUALITY = 82
EXTENSIONS = (".jpg", ".jpeg", ".png", ".webp")

# folder (not recursive) -> target widths in pixels; images are never enlarged
FOLDERS = {
    "img/video_thumbnails": [640, 1100],
    "img/stills/thumbnails": [640],
    "img/stills": [1000, 2000],
    "img/more": [900, 1500],
}


def variants_for(width, targets):
    """Widths to produce for an image `width` pixels wide."""
    widths = [t for t in targets if t < width * 0.87]
    largest = min(width, targets[-1])
    if largest not in widths:
        widths.append(largest)
    return widths


def main():
    manifest = {}
    written = skipped = 0
    for folder, targets in FOLDERS.items():
        src_dir = os.path.join(ROOT, folder)
        dst_rel = OUT_DIR + folder[len("img"):]
        os.makedirs(os.path.join(ROOT, dst_rel), exist_ok=True)
        for name in sorted(os.listdir(src_dir)):
            ext = os.path.splitext(name)[1]
            src = os.path.join(src_dir, name)
            if ext.lower() not in EXTENSIONS or not os.path.isfile(src):
                continue
            with Image.open(src) as opened:
                icc = opened.info.get("icc_profile")
                im = ImageOps.exif_transpose(opened)
                im = im.convert("RGBA" if im.mode in ("RGBA", "LA", "P") else "RGB")
                w, h = im.size
                widths = variants_for(w, targets)
                entries = []
                for vw in widths:
                    vh = round(h * vw / w)
                    suffix = "" if vw == widths[-1] else "-%d" % vw
                    rel = "%s/%s%s.webp" % (dst_rel, name, suffix)
                    dst = os.path.join(ROOT, rel)
                    if os.path.exists(dst) and os.path.getmtime(dst) >= os.path.getmtime(src):
                        skipped += 1
                    else:
                        resized = im if vw == w else im.resize((vw, vh), Image.LANCZOS)
                        resized.save(dst, "WEBP", quality=QUALITY, method=6, icc_profile=icc)
                        written += 1
                    entries.append((vw, vh, rel))
            # w/h are the ORIGINAL's dimensions, so the page lays the image out exactly
            # as it would the original file
            item = {"src": entries[-1][2], "w": w, "h": h}
            if len(entries) > 1:
                item["srcset"] = ", ".join("%s %dw" % (r, ew) for ew, _, r in entries)
            manifest[folder + "/" + name] = item

    with open(os.path.join(ROOT, MANIFEST), "w") as f:
        f.write("// Generated by tools/optimize-images.py. Do not edit by hand.\n")
        f.write("window.IMAGE_MANIFEST = ")
        f.write("{\n" + ",\n".join(
            "%s: %s" % (json.dumps(k), json.dumps(v, sort_keys=True)) for k, v in sorted(manifest.items())) + "\n}")
        f.write(";\n")
    print("%d images in manifest, %d files written, %d already up to date" % (len(manifest), written, skipped))


if __name__ == "__main__":
    sys.exit(main())
